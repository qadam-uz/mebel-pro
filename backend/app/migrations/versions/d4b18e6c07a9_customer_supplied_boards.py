"""Customer-supplied boards: sheets a walk-in brings that the branch does not sell.

Five columns on `branch_materials`, a partial unique index, and one seeded
manufacturer + dekor the boards all point at.

The index change is the load-bearing part. `uq_branch_materials_branch_dekor_format`
says a branch carries one row per (dekor, format). Every customer board points at
the single seeded `Mijoz` dekor, so two walk-ins bringing 2750x1830x16 to the same
branch produce an identical tuple and the second insert would be rejected. The
predicate scopes uniqueness to rows the branch actually carries, which is what the
constraint always meant.

Hand-written, not autogenerated: autogenerate emits the `add_column` calls and
nothing else — not the index predicate, not the seed.
"""

