    # The non-partial index cannot be restored while customer rows exist — they
    # are exactly the rows the predicate was added to allow. Fail loudly rather
    # than dropping somebody's orders on the floor.
    remaining = bind.execute(
        sa.text("SELECT count(*) FROM branch_materials WHERE customer_supplied")
    ).scalar_one()
    if remaining:
        raise RuntimeError(
            f"{remaining} customer-supplied branch materials exist; "
            "delete them before downgrading or the unique index cannot be restored"
        )

    op.drop_index(_INDEX, table_name="branch_materials")
    op.create_index(
        _INDEX,
        "branch_materials",
        [
            "branch_id",
            "dekor_id",
            "qalinlik_mm",
            sa.text("coalesce(uzunlik_mm, 0)"),
            sa.text("coalesce(eni_mm, 0)"),
            sa.text("coalesce(kromka_eni_mm, 0)"),
        ],
        unique=True,
    )

    op.drop_index("ix_branch_materials_source_draft", table_name="branch_materials")
    op.drop_constraint("fk_branch_materials_stock_material", "branch_materials", type_="foreignkey")
    op.drop_constraint("fk_branch_materials_source_draft", "branch_materials", type_="foreignkey")
    op.drop_column("branch_materials", "stock_material_id")
    op.drop_column("branch_materials", "source_draft_id")
    op.drop_column("branch_materials", "tolali")
    op.drop_column("branch_materials", "nomi")
    op.drop_column("branch_materials", "customer_supplied")

