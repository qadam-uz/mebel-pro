// Generates every static brand asset from the @theme tokens in
// src/assets/main.css — the single source of the mark's colours:
//   --color-brand-tile   → the tile (deliberately NOT --color-accent)
//   --color-brand-panel  → the sheet parts (cream board)
//   --color-brand-wood   → the one wood-amber part
//
// Outputs (all under public/):
//   favicon.svg              vector mirror, literal hex (an icon SVG renders
//                            with no CSS custom properties available)
//   favicon.ico              16 + 32 + 48 PNG-compressed entries
//   apple-touch-icon-180.png full-bleed square (iOS rounds it itself)
//   icon-192.png, icon-512.png   rounded tile on transparency
//   maskable-512.png         full-bleed, parts held inside the 80% safe zone
//
// Run: node scripts/generate-brand-assets.mjs
// Zero dependencies on purpose: the mark is four rounded rects, so the script
// carries its own supersampled rasterizer and a minimal PNG/ICO writer rather
// than pulling a native image library into the toolchain for it.
// BrandMark.vue draws the same geometry live from the tokens; change a token
// value → rerun this script, never hand-edit the outputs (DESIGN.md, Brand).

import { readFileSync, writeFileSync } from 'node:fs'
import { deflateSync } from 'node:zlib'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const webRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(join(webRoot, 'src/assets/main.css'), 'utf8')

function token(name) {
  const m = css.match(new RegExp(`${name}:\\s*(#[0-9a-fA-F]{6})\\s*;`))
  if (!m) throw new Error(`token ${name} not found in main.css`)
  return m[1].toLowerCase()
}

const TILE = token('--color-brand-tile')
const PANEL = token('--color-brand-panel')
const WOOD = token('--color-brand-wood')

// The mark's geometry on the canonical 32-unit grid (BrandMark.vue holds the
// same numbers): tile r7, then left tall part, right top part, right bottom
// (wood) part, all r2.
const TILE_RECT = { x: 0, y: 0, w: 32, h: 32, r: 7 }
const PARTS = [
  { x: 5, y: 5, w: 9, h: 22, r: 2, fill: () => PANEL },
  { x: 16.5, y: 5, w: 10.5, h: 10, r: 2, fill: () => PANEL },
  { x: 16.5, y: 17, w: 10.5, h: 10, r: 2, fill: () => WOOD },
]

// ── favicon.svg ────────────────────────────────────────────────────────────
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" role="img" aria-label="Mebel Pro">
  <title>Mebel Pro</title>
  <!-- GENERATED by scripts/generate-brand-assets.mjs from the @theme brand
       tokens in src/assets/main.css — do not hand-edit; change the tokens and
       rerun. The mark is the cutting map: a sheet of parts on the brand
       tile, one part in wood amber. BrandMark.vue draws the same geometry
       live from the tokens. -->
  <rect width="32" height="32" rx="7" fill="${TILE}"/>
  <rect x="5" y="5" width="9" height="22" rx="2" fill="${PANEL}"/>
  <rect x="16.5" y="5" width="10.5" height="10" rx="2" fill="${PANEL}"/>
  <rect x="16.5" y="17" width="10.5" height="10" rx="2" fill="${WOOD}"/>
</svg>
`
writeFileSync(join(webRoot, 'public/favicon.svg'), svg)

// ── Rasterizer: supersampled rounded-rect coverage ─────────────────────────
function hexToRgb(hex) {
  return [
    parseInt(hex.slice(1, 3), 16),
    parseInt(hex.slice(3, 5), 16),
    parseInt(hex.slice(5, 7), 16),
  ]
}

function insideRoundedRect(px, py, rect) {
  const { x, y, w, h, r } = rect
  if (px < x || px > x + w || py < y || py > y + h) return false
  const cx = Math.max(x + r, Math.min(px, x + w - r))
  const cy = Math.max(y + r, Math.min(py, y + h - r))
  const dx = px - cx
  const dy = py - cy
  return dx * dx + dy * dy <= r * r || (px >= x + r && px <= x + w - r) || (py >= y + r && py <= y + h - r)
}

/**
 * Renders the mark into an RGBA buffer.
 * size    — output pixels
 * layout  — maps the 32-unit grid into the output square:
 *   scale, offset (px), and whether the tile itself is drawn full-bleed
 *   (no radius, covering the whole square) instead of as a rounded tile.
 */
function renderMark(size, { scale, offset, fullBleedTile }) {
  const SS = 4 // 4×4 subsamples per pixel
  const buf = Buffer.alloc(size * size * 4)
  const tileRgb = hexToRgb(TILE)
  const layers = PARTS.map((p) => ({
    rect: {
      x: p.x * scale + offset,
      y: p.y * scale + offset,
      w: p.w * scale,
      h: p.h * scale,
      r: p.r * scale,
    },
    rgb: hexToRgb(p.fill()),
  }))
  const tileRect = fullBleedTile
    ? null
    : { x: 0, y: 0, w: size, h: size, r: TILE_RECT.r * (size / 32) }

  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let rAcc = 0
      let gAcc = 0
      let bAcc = 0
      let aAcc = 0
      for (let sy = 0; sy < SS; sy++) {
        for (let sx = 0; sx < SS; sx++) {
          const px = x + (sx + 0.5) / SS
          const py = y + (sy + 0.5) / SS
          let rgb = null
          if (fullBleedTile || insideRoundedRect(px, py, tileRect)) rgb = tileRgb
          if (rgb) {
            for (const layer of layers) {
              if (insideRoundedRect(px, py, layer.rect)) rgb = layer.rgb
            }
            rAcc += rgb[0]
            gAcc += rgb[1]
            bAcc += rgb[2]
            aAcc += 255
          }
        }
      }
      const n = SS * SS
      const i = (y * size + x) * 4
      const a = aAcc / n
      // Straight (non-premultiplied) alpha, as PNG requires: average the
      // colour over covered subsamples only.
      const covered = aAcc / 255 || 1
      buf[i] = Math.round(rAcc / covered)
      buf[i + 1] = Math.round(gAcc / covered)
      buf[i + 2] = Math.round(bAcc / covered)
      buf[i + 3] = Math.round(a)
    }
  }
  return buf
}

// ── Minimal PNG writer (RGBA8, filter 0, one IDAT) ─────────────────────────
const CRC_TABLE = new Int32Array(256).map((_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c
})

function crc32(buf) {
  let c = -1
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8)
  return (c ^ -1) >>> 0
}

function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}

function encodePng(rgba, size) {
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // colour type RGBA
  const raw = Buffer.alloc(size * (size * 4 + 1))
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0 // filter: none
    rgba.copy(raw, y * (size * 4 + 1) + 1, y * size * 4, (y + 1) * size * 4)
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ])
}

function pngOfMark(size, layout) {
  return encodePng(renderMark(size, layout), size)
}

// Rounded tile on transparency, mark filling the square.
const roundedLayout = (size) => ({ scale: size / 32, offset: 0, fullBleedTile: false })
// Full-bleed square: the tile colour floods the canvas, parts scaled/centred.
const fullBleedLayout = (size, contentRatio) => {
  const scale = (size * contentRatio) / 32
  return { scale, offset: (size - 32 * scale) / 2, fullBleedTile: true }
}

writeFileSync(join(webRoot, 'public/icon-192.png'), pngOfMark(192, roundedLayout(192)))
writeFileSync(join(webRoot, 'public/icon-512.png'), pngOfMark(512, roundedLayout(512)))
// iOS rounds the corners itself; parts keep their standard inset (32-grid = full).
writeFileSync(
  join(webRoot, 'public/apple-touch-icon-180.png'),
  pngOfMark(180, fullBleedLayout(180, 1)),
)
// Maskable: any mask may crop to an 80% circle, so the sheet pulls in to 62%.
writeFileSync(
  join(webRoot, 'public/maskable-512.png'),
  pngOfMark(512, fullBleedLayout(512, 0.62)),
)

// ── favicon.ico: 16/32/48, PNG-compressed entries ──────────────────────────
const icoSizes = [16, 32, 48]
const icoPngs = icoSizes.map((s) => pngOfMark(s, roundedLayout(s)))
const header = Buffer.alloc(6)
header.writeUInt16LE(0, 0) // reserved
header.writeUInt16LE(1, 2) // type: icon
header.writeUInt16LE(icoSizes.length, 4)
let dataOffset = 6 + icoSizes.length * 16
const entries = []
for (let i = 0; i < icoSizes.length; i++) {
  const e = Buffer.alloc(16)
  e[0] = icoSizes[i] === 256 ? 0 : icoSizes[i] // width
  e[1] = icoSizes[i] === 256 ? 0 : icoSizes[i] // height
  e[2] = 0 // palette
  e[3] = 0 // reserved
  e.writeUInt16LE(1, 4) // colour planes
  e.writeUInt16LE(32, 6) // bits per pixel
  e.writeUInt32LE(icoPngs[i].length, 8)
  e.writeUInt32LE(dataOffset, 12)
  dataOffset += icoPngs[i].length
  entries.push(e)
}
writeFileSync(join(webRoot, 'public/favicon.ico'), Buffer.concat([header, ...entries, ...icoPngs]))

console.log(
  `brand assets generated from tokens: tile ${TILE}, panel ${PANEL}, wood ${WOOD}\n` +
    'wrote public/favicon.svg, favicon.ico, apple-touch-icon-180.png, icon-192.png, icon-512.png, maskable-512.png',
)
